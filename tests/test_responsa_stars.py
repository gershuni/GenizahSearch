# --- A star at the start of a word (the second PR: Phase 1's meaning lifted) ---------------

@pytest.mark.parametrize('query', ['*כ*נים', '*כ*ה*נ*ים', '*כהנים*גדולים', '(*נים/כהנים)',
                                   '*(כהנים/גדולים)', '-*כ*נים', '*כהנ*', '*נים'])
def test_a_word_that_begins_with_a_star_is_searched_in_every_shape(query):
    c = _compiled(query)
    assert c.warning is None
    assert all(isinstance(f, StarForm) for p in c.plans for f in p.stems if '*' in getattr(f, 'typed', f))


def test_a_supported_true_star_is_no_longer_rewritten():
    # §8: Phase 1 rewrote *X* as #X# with the warning "*word* rewritten as #word#", and
    # read *X as X with its 24 grammatical prefixes. A true star is searched as typed:
    # *כהנ* finds ואלכהנות and *כהנים finds אלכהנים -- neither is made by a prefix or a
    # suffix of the list.
    c = _compiled('*כהנ*')
    assert c.warning is None
    comp = c.plans[0].component
    assert not comp.grammatical_prefixes and not comp.grammatical_suffixes
    sf, = c.plans[0].stems
    assert isinstance(sf, StarForm) and sf.typed == '*כהנ*'
    assert accepted('*כהנ*', 'שם ואלכהנות שם') == 'ואלכהנות'
    assert accepted('#כהנ#', 'שם ואלכהנות שם') is None
    sf, = _compiled('*כהנים').plans[0].stems
    assert isinstance(sf, StarForm) and sf.runs == (('',), ('כהנים',))
    assert accepted('*כהנים', 'שם אלכהנים שם') == 'אלכהנים'
    assert accepted('*כהנים', 'שם 3כהנים שם') is None          # the star takes letters only


