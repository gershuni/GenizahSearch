def _lookup_pages(eng, query):
    """The page documents the compiled lookup returns (stage 1, no check)."""
    c = _compiled(query)
    q = c.retrieval(eng.index, has_content_search=True, reversed_field=eng._reversed_words_field(eng.index))
    q = tantivy.Query.boolean_query([(tantivy.Occur.Must, q),
                                     (tantivy.Occur.Must, eng.index.parse_query('scope:page', ['content']))])
    return {eng.searcher.doc(a)['unique_id'][0] for _, a in eng.searcher.search(q, 1000).hits}


