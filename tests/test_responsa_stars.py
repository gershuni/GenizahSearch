def test_the_reversed_route_is_the_one_used_on_format_2(engines, monkeypatch):
    # With the reversed field's lookup broken, format 2 loses the leading-star pages and
    # format 1 (the scan) does not: the reversed field is what format 2 reads.
    real = rm.star_pattern

    def broken(sf, tolerance, fold=True, reverse=False):
        return 'nothing-matches-this' if reverse else real(sf, tolerance, fold, reverse)
    monkeypatch.setattr(rm, 'star_pattern', broken)
    assert _lookup_pages(engines['2'], '*נים') == set()
    assert _lookup_pages(engines['1'], '*נים') == {page(n) for n in (1, 2, 3, 4, 5, 6, 7, 8, 11)}


def test_a_pattern_past_the_size_limit_is_split_into_several_queries(engines, monkeypatch):
    # Decision 5: variants and Judeo-Arabic on a star word are several regex_querys ORed,
    # each within tantivy-fst's limit. Forced here with a chunk of one form per run.
    eng = engines['2']
    want = _lookup_pages(eng, 'כ*נים#')
    c = _compiled('כ*נים#')
    monkeypatch.setattr(rm, '_PATTERN_CHUNK', 5)
    queries = rm.star_queries(c.plans[0].starred, eng.index.schema, 'content_search', rm._T_CONTENT_SEARCH)
    # The suffix run's 25 forms halved until no part holds more than 5: 12 + 13, then
    # 6 + 6 + 6 + 7, then eight parts of 3 or 4.
    assert len(queries) == 8
    assert _lookup_pages(eng, 'כ*נים#') == want and want


def test_a_reversed_pattern_past_the_size_limit_is_split_too(engines, monkeypatch):
    # The same on the reversed-words field: *נים#'s suffix run, read backwards.
    eng = engines['2']
    want = _lookup_pages(eng, '*נים#')
    c = _compiled('*נים#')
    monkeypatch.setattr(rm, '_PATTERN_CHUNK', 5)
    queries = rm.star_queries(c.plans[0].starred, eng.index.schema, 'content_search', rm._T_CONTENT_SEARCH,
                              eng._reversed_words_field(eng.index))
    assert len(queries) == 8
    assert _lookup_pages(eng, '*נים#') == want and want


# --- End to end: page rows, both formats and both runtimes ----------------------------------

def _page_rows(eng, query, runtime, **opts):
    def run():
        return eng.execute_search(query, 'literal', 0, responsa_options=dict(R, **opts), corpus_scope='genizah')
    if runtime == 're':
        with isolated_matching(native=True):
            rows = run()
    else:
        rows = run()
    return {r['uid'] for r in rows if not r.get('cross_page')}


