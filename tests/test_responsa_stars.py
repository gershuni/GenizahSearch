"""True `*` in Responsa (docs/plans/RESPONSA_TRUE_WILDCARDS_PLAN.md, Phase 3, §7 and its
"settled before building" points): any letters inside one word, zero included, at the end
of a word or inside it, as often as typed. A star at the start of a word keeps Phase 1's
meaning until the reversed-words field is searched (point 14): `*X` the prefix list, `*X*`
rewritten as `#X#`, any other word that begins with a star refused.

- the parser and the compiler: every star position and its combinations with `#`, `%`,
  `-`, OR groups and inline alternation; expansion run by run; bare stars refused, short
  star words warned (decision 4);
- the check on both regex runtimes: letters only, never a digit, `_` or a space;
- retrieval per shape on both index formats (tests/responsa_index_fixture.py builds one
  corpus with the real Indexer as format 2 and as format 1);
- end to end, trailing and middle stars, on both formats and both runtimes.
Matches across pages: tests/test_responsa_star_crossings.py.

Every expectation is written by hand from the corpus below, never generated by the code.
"""
import re

import pytest
import regex
import tantivy

import shared.responsa_match as rm
import shared.search_engine as se
from shared.responsa import parse_responsa_query, extract_per_pair_gaps
from shared.responsa_match import (
    ResponsaQueryRefused, StarExclusion, StarForm, compile_components, expand_stems, typed_forms,
)
from shared.search_regex import isolated_matching
from tests.responsa_index_fixture import formats, uid

RUNTIMES = ['re', 'regex']
R = {"responsa_mode": True}


def _compiled(query, **opts):
    comps = parse_responsa_query(query)
    return compile_components(comps, dict(R, **opts), None, 0, extract_per_pair_gaps(query),
                              query_has_brackets=se._query_has_brackets(query))


def accepted(query, text, runtime='re', **opts):
    """The text of the first match a row would use, or None."""
    c = _compiled(query, **opts)
    if runtime == 're':
        rx = re.compile(c.check_pattern, c.flags)
    else:
        rx = regex.compile(c.check_pattern, regex.I | regex.V0)
    m = rx.search(text)
    while m is not None and not c.accept(text, m):
        m = rx.search(text, m.start() + 1)
    return m.group(0) if m else None


# --- The parser: every star position, and with #, %, -, OR groups ------------------------

@pytest.mark.parametrize('query, wildcard, typed, flags', [
    ('*נים', 'prefix', ['*נים'], ''),
    ('כהנ*', 'suffix', ['כהנ*'], ''),
    ('כהנ**', 'suffix', ['כהנ*'], ''),                     # stars in a row are one
    ('כ*נים', 'pattern', ['כ*נים'], ''),                   # inside a word
    ('*כהנ*', 'pattern', ['*כהנ*'], ''),                   # both ends
    ('כ*ה*נ*ים', 'pattern', ['כ*ה*נ*ים'], ''),             # several
    ('#כ*נים', 'pattern', ['כ*נים'], '#'),
    ('כ*נים#', 'pattern', ['כ*נים'], 's'),
    ('%כ*נים', 'pattern', ['כ*נים'], '%'),
    ('#כהנ*#', 'suffix', ['כהנ*'], '#s'),
    ('-כ*נים', 'pattern', ['כ*נים'], '-'),
    ('(כהנ*/לוי)', None, ['כהנ*', 'לוי'], ''),           # an OR group with a star word
    ('(כהנ/גדול)*', 'suffix', ['כהנ*', 'גדול*'], ''),     # the group's trailing star
    ('כה(נ/ן)*', None, ['כהנ*', 'כהן*'], ''),             # an inline alternation
])
def test_the_parser_reads_every_star_position(query, wildcard, typed, flags):
    comp, = parse_responsa_query(query)
    assert comp.wildcard == wildcard
    assert typed_forms(comp) == typed
    assert comp.grammatical_prefixes == ('#' in flags)
    assert comp.grammatical_suffixes == ('s' in flags)
    assert comp.plene_defective == ('%' in flags)
    assert comp.negated == ('-' in flags)


# --- Expansion run by run (plan §7, Phase 3 point 2) --------------------------------------

def _runs(query, ja=False):
    comp, = parse_responsa_query(query)
    forms = expand_stems(comp, False, ja, 'exact', None)
    return [f.runs for f in forms if isinstance(f, StarForm)], [f for f in forms if not isinstance(f, StarForm)]


def test_hash_prefixes_go_on_the_first_run_and_suffixes_on_the_last():
    (runs,), finite = _runs('#כ*נים#')
    assert not finite
    assert len(runs) == 2
    assert {'כ', 'הכ', 'וכ', 'שכ', 'כשהכ'} <= set(runs[0]) and len(runs[0]) == 24
    assert {'נים', 'נימה', 'נימות', 'נימיהם'} <= set(runs[1]) and len(runs[1]) == 25


def test_a_trailing_star_takes_the_suffixes_and_judeo_arabic_goes_on_the_first_run():
    # כהנ*#: the star already takes every suffix -- only the first run expands.
    (runs,), _ = _runs('כהנ*#')
    assert runs == (('כהנ',), ('',))
    (runs,), _ = _runs('כהנ*', ja=True)
    assert set(runs[0]) == {'כהנ', 'אלכהנ', 'ואלכהנ', 'באלכהנ', 'פאלכהנ', 'כאלכהנ', 'לאלכהנ', 'ללכהנ'}
    assert runs[1] == ('',)


def test_plene_defective_expands_every_run():
    (runs,), _ = _runs('%כהנ*גדול')
    assert {'כהנ', 'כוהנ', 'כיהנ'} <= set(runs[0])
    assert {'גדול', 'גדל', 'גידול'} <= set(runs[1])


def test_the_guard_counts_the_sum_of_the_runs_not_the_product():
    comp, = parse_responsa_query('#כ*נים#')
    sf, = expand_stems(comp, False, False, 'exact', None)
    assert sf.cost == 24 + 25          # the product would be 600
    assert rm.term_cost([sf, 'גדולים']) == 50


# --- Refusals and warnings (decision 4) ----------------------------------------------------

@pytest.mark.parametrize('query', ['*', '**', 'כהנים *', '(*/כהנים)', '-*', '#*#'])
def test_a_bare_star_is_refused_and_the_message_suggests_a_gap(query):
    with pytest.raises(ResponsaQueryRefused) as info:
        _compiled(query)
    assert info.value.code == 'responsa_unsupported_star'
    assert '[1]' in str(info.value)


@pytest.mark.parametrize('query', ['כ*נ.ים', 'א*ב,ג'])
def test_a_star_word_with_punctuation_inside_is_refused(query):
    # A star never reaches past punctuation, and the lookup reads one token per word.
    with pytest.raises(ResponsaQueryRefused) as info:
        _compiled(query)
    assert info.value.code == 'responsa_unsupported_star'


@pytest.mark.parametrize('query, warned', [('כ*', True), ('כה*', True), ('ש*ם', True), ('כהנ*', False),
                                           ('כה* גדולים', True), ('כ*ן', True), ('כ*הן', False),
                                           ('כהנים', False)])
def test_a_star_word_with_one_or_two_letters_of_its_own_runs_with_a_warning(query, warned):
    c = _compiled(query)
    assert bool(c.warning and 'N+' in c.warning) == warned


# --- A star at the start of a word keeps Phase 1's meaning (point 14) ----------------------

@pytest.mark.parametrize('query', ['*כ*נים', '*כ*ה*נ*ים', '*כהנים*גדולים', '(*נים/כהנים)',
                                   '*(כהנים/גדולים)', '-*כ*נים'])
def test_a_leading_star_with_another_star_is_refused_for_now(query):
    with pytest.raises(ResponsaQueryRefused) as info:
        _compiled(query)
    assert info.value.code == 'responsa_unsupported_star'
    assert 'start of a word' in str(info.value)


def test_star_word_is_the_prefix_list_and_star_word_star_is_hash_word_hash():
    c = _compiled('*כהנים')
    plan, = c.plans
    assert plan.legacy_prefix and not plan.starred and c.warning is None
    assert {'הכהנים', 'וכהנים', 'כהנים'} <= set(plan.terms())     # the 24-prefix list, as Phase 1
    assert accepted('*כהנים', 'שם אלכהנים שם') == 'אלכהנים'        # \S*X, as Phase 1
    c = _compiled('*כהנ*')
    assert c.warning and 'rewritten' in c.warning
    comp = c.plans[0].component
    assert comp.grammatical_prefixes and comp.grammatical_suffixes


# --- The check: letters only, zero included, on both runtimes ------------------------------

@pytest.mark.parametrize('runtime', RUNTIMES)
@pytest.mark.parametrize('query, text, want', [
    ('מאמ* קור*', 'אמר מאמתי קורין את', 'מאמתי קורין'),
    ('מאמ* קור*', 'מאמ קור', 'מאמ קור'),                        # a star takes zero letters
    ('מאמ* קור*', 'מאמ12 קורין', None),                         # never a digit
    ('מאמ* קור*', 'מאמ_ קורין', None),                          # never _
    ('מאמ* קור*', 'המאמר קורא', None),                          # the word must begin with מאמ
    ('מאמ* קור*', 'מאמר, קורא', 'מאמר, קורא'),
    ('כ*נים גדולים', 'כנים גדולים', 'כנים גדולים'),
    ('כ*נים גדולים', 'הכהנים גדולים', None),
    ('כ*נים גדולים', 'כה"נים גדולים', 'כה"נים גדולים'),         # a quote inside a star
    ('כ*נים גדולים', 'כ1נים גדולים', None),
    ('כ*נים', 'כ נים', None),                                    # never a space
    ('כ*ה*נ*ים גדולים', 'כוהנים גדולים', 'כוהנים גדולים'),
    ('כ*ה*נ*ים גדולים', 'כֹּהֲנִים גדולים', 'כֹּהֲנִים גדולים'),     # marks go with the letters
    ('כ*ה*נ*ים גדולים', 'כהניםא גדולים', None),                 # the word ends in א
    ('כהנים*', 'כֹּהֲנִים', None),                                  # a literal run is not point-tolerant
    ('שלום*', 'שלומות רבות', 'שלומות'),                         # a final letter before a star
    ('שלומ*', 'שלום רב', 'שלום'),                               # and a medial one
    ('כ*נ*', 'שם כאנות שם', 'כאנות'),
    ('כ*נים', 'שם כ\U00010400נים שם', 'כ\U00010400נים'),     # a letter past the first plane
    ('(כהנ*/לוי) גדול', 'לוי גדול', 'לוי גדול'),
    ('(כהנ*/לוי) גדול', 'כהניא גדול', 'כהניא גדול'),
])
def test_the_check(runtime, query, text, want):
    assert accepted(query, text, runtime) == want


@pytest.mark.parametrize('runtime', RUNTIMES)
def test_the_highlight_marks_the_star_word(runtime):
    c = _compiled('מאמ* קור*')
    rx = re.compile(c.highlight_pattern, re.I) if runtime == 're' else regex.compile(c.highlight_pattern, regex.I)
    assert [m.group(0) for m in rx.finditer('אמר מאמתי קורין את')] == ['מאמתי קורין']


def test_a_negated_star_word_takes_its_plene_and_defective_spellings_with_percent():
    # Codex review of PR #443: -%כ*נים excludes כנם too, as %כ*נים finds it (point 2).
    ex, = _compiled('כהנים -%כ*נים').negated_words
    assert ex.found_in('שם כנם') and ex.found_in('שם כוהנים')
    plain, = _compiled('כהנים -כ*נים').negated_words
    assert not plain.found_in('שם כנם') and plain.found_in('שם כוהנים')


def test_a_negated_star_word_excludes_letters_matching_it_anywhere():
    c = _compiled('כהנים -כ*נים -גדול*')
    ex, plain = c.negated_words
    assert isinstance(ex, StarExclusion) and ex == 'כ*נים'
    assert plain == 'גדול' and not isinstance(plain, StarExclusion)     # an edge star adds nothing
    assert ex.found_in('שם אלכהנים')          # letters anywhere, inside a longer word
    assert not ex.found_in('כ הנים')          # a star never takes a space
    assert not ex.found_in('כ1נים')


