"""Responsa Phase 1: one meaning on every path, for finite words (plan §4, §5.1-5.3, §7).

docs/plans/RESPONSA_TRUE_WILDCARDS_PLAN.md. A real Tantivy fixture (tests/responsa_fixture.py):
page docs, a whole-manuscript doc over two of them, and the same pages as a LOCAL index.
Every expectation below is written by hand, never generated by the compiler.
"""
import pytest

tantivy = pytest.importorskip("tantivy")

from tests.responsa_fixture import build_local, build_main, make_engine, release, witnesses  # noqa: E402
from shared.responsa_match import ResponsaQueryRefused  # noqa: E402

R = {"responsa_mode": True}

PAGES = {
    "990001": [("edge_no", "אמרו כהנים גדולים עמדו"),          # כהנים גדול: no (גדולים goes on)
               ("edge_yes", "אמר כהנים גדול.")],              # כהנים גדול: yes
    "990002": [("inside", "בספרים רבים"),                      # a lone ספר: no
               ("word", "ספר תורה")],                           # a lone ספר: yes
    "990003": [("bracket_in", "של[ו]ם עליכם")],                 # שלום: kept, marked with its bracket
    "990004": [("prefixed", "הכהנים גדולים")],                  # #כהנ# גדולים: yes; כהנים גדולים: no
    "990005": [("suffixed", "וכהניהם גדולים")],                 # #כהנ# גדולים: yes (a suffix)
    "990006": [("short_form", "כהני העם")],                     # #כהנ#: the short form כהני
    "990007": [("and_far", "ראובן בא\nואחר כך\nשמעון יצא"),      # ראובן AND שמעון: yes
               ("and_inside", "ראובני ושמעוני")],                # no: both inside longer words
    "990008": [("reversed", "דהו אבג"),                         # אבג דהו bidirectional: yes
               ("reversed_inside", "דהוי אבג")],                 # no: the reverse branch is bounded
    "990009": [("cross_a", "תחילה כהנים"), ("cross_b", "גדולים סוף")],   # a crossing
    "990010": [("line", "שורה ראשונה\nשנייה כאן"),               # ראשונה | שנייה
               ("line_inside", "שורה ראשונהא\nשנייה כאן")],      # no: ראשונהא goes on
    # flex: שלום עולם joined (the page also holds both words apart, so the lookup --
    # which reads whole tokens -- returns it; a page with the joined form only is not
    # a candidate, today as before)
    "990011": [("flex", "שלוםעולם כאן שלום רב עולם")],
    "990012": [("negated", "כהנים גדולים ואלכהנים")],           # -אלכהנים hides it
    "990013": [("gap", "ספר תורה תורהו")],                      # ספר [2] תורה: backtracks
    "990014": [("quote_inside", 'ס"פר כאן')],                   # ספר: the quote is looked past
}
ALL_PAGES = [p for pages in PAGES.values() for p in pages]


@pytest.fixture(scope="module")
def engines(tmp_path_factory):
    root = tmp_path_factory.mktemp("responsa_ww")
    build_main(root, PAGES)
    local_dir = str(root / "LocalIndex")
    build_local(local_dir, ALL_PAGES)
    eng = make_engine(root, local_dir)
    yield eng
    release(eng)


def _search(eng, query, scope="genizah", **opts):
    return eng.execute_search(query, "literal", 0, responsa_options=dict(R, **opts), corpus_scope=scope)


def _uids(rows):
    return {r["uid"] for r in rows}


# --- Whole words, the first and last included (§4) --------------------------------------

def test_the_last_word_is_a_whole_word(engines):
    uids = _uids(_search(engines, "כהנים גדול"))
    assert "edge_yes" in uids
    assert "edge_no" not in uids


def test_a_lone_word_is_a_whole_word(engines):
    uids = _uids(_search(engines, "ספר"))
    assert {"word", "quote_inside"} <= uids
    assert "inside" not in uids


def test_the_first_word_is_a_whole_word(engines):
    assert "prefixed" not in _uids(_search(engines, "כהנים גדולים"))


def test_a_gap_query_backtracks_to_the_whole_word(engines):
    rows = {r["uid"]: r for r in _search(engines, "ספר [2] תורה")}
    assert "*ספר תורה* תורהו" in rows["gap"]["raw_file_hl"]


# --- #X# keeps its suffixes (§5.3) -------------------------------------------------------

def test_hash_both_sides_keeps_the_suffixes(engines):
    rows = _search(engines, "#כהנ# גדולים")
    uids = _uids(rows)
    assert {"prefixed", "suffixed"} <= uids
    assert not (rows and rows[0].get("responsa_warning"))


def test_a_short_form_that_prefixes_a_longer_one_is_kept(engines):
    assert "short_form" in _uids(_search(engines, "#כהנ#"))


# --- Brackets: one rule (§4) -------------------------------------------------------------

def test_a_bracket_inside_the_word_is_kept_and_marked_where_it_stands(engines):
    rows = {r["uid"]: r for r in _search(engines, "שלום")}
    assert "bracket_in" in rows
    assert "*של[ו]ם*" in rows["bracket_in"]["raw_file_hl"]


def test_the_bracket_rule_holds_on_my_library_too(engines):
    rows = {r["uid"]: r for r in _search(engines, "שלום", scope="local")}
    assert "bracket_in" in rows
    assert "*של[ו]ם*" in rows["bracket_in"]["raw_file_hl"]


# --- AND, bidirectional, flex spacing, lines ---------------------------------------------

def test_every_and_operand_is_a_whole_word(engines):
    uids = _uids(_search(engines, "ראובן AND שמעון"))
    assert "and_far" in uids
    assert "and_inside" not in uids


def test_both_bidirectional_branches_are_bounded(engines):
    uids = _uids(_search(engines, "אבג דהו", bidirectional=True))
    assert "reversed" in uids
    assert "reversed_inside" not in uids


def test_flex_spacing_bounds_only_the_joined_unit(engines):
    assert "flex" in _uids(_search(engines, "שלום עולם", flex_spacing=True))
    assert "flex" not in _uids(_search(engines, "שלום עולם"))


def test_a_line_row_marks_its_words_not_the_whole_lines(engines):
    rows = {r["uid"]: r for r in _search(engines, "ראשונה | שנייה")}
    assert "שורה *ראשונה\nשנייה* כאן" in rows["line"]["raw_file_hl"]


def test_a_line_group_is_bounded_at_its_edges(engines):
    uids = _uids(_search(engines, "ראשונה | שנייה"))
    assert "line" in uids
    assert "line_inside" not in uids


# --- Crossings and negation --------------------------------------------------------------

def test_a_match_across_a_page_break_is_found(engines):
    rows = [r for r in _search(engines, "כהנים גדולים") if r.get("cross_page")]
    assert [r["uid"] for r in rows] == ["cross_a"]
    assert "*כהנים\nגדולים*" in rows[0]["raw_file_hl"]


def test_a_negated_word_hides_a_row(engines):
    assert "negated" in _uids(_search(engines, "כהנים גדולים"))
    assert "negated" not in _uids(_search(engines, "כהנים גדולים -אלכהנים"))


# --- One meaning on main and LOCAL (gate 3: their common domain, one page) ---------------

@pytest.mark.parametrize("query, opts", [
    ("כהנים גדול", {}), ("ספר", {}), ("#כהנ# גדולים", {}), ("#כהנ#", {}), ("שלום", {}),
    ("ראובן AND שמעון", {}), ("אבג דהו", {"bidirectional": True}),
    ("שלום עולם", {"flex_spacing": True}), ("ספר [2] תורה", {}),
])
def test_main_and_local_give_the_same_witnesses_inside_one_page(engines, query, opts):
    main = witnesses([r for r in _search(engines, query, **opts) if not r.get("cross_page")])
    local = witnesses(_search(engines, query, scope="local", **opts))
    assert main == local


def test_a_crossing_is_main_only_by_design(engines):
    local = _uids(_search(engines, "כהנים גדולים", scope="local"))
    assert "cross_a" not in local and "cross_b" not in local


# --- Refused star shapes (Phase 1) -------------------------------------------------------

@pytest.mark.parametrize("query", ["כ*נים", "*", "**", "*כ*ה*נ*ים", "כהנים *א*ב", "(כ*ן/לוי)", "ראשונה | כ*ן"])
@pytest.mark.parametrize("scope", ["genizah", "local", "all"])
def test_an_unsupported_star_is_refused_with_a_message_on_every_path(engines, query, scope):
    with pytest.raises(ResponsaQueryRefused) as info:
        _search(engines, query, scope=scope)
    assert info.value.code == "responsa_unsupported_star"
    assert str(info.value)


@pytest.mark.parametrize("query", ["*כהנים", "גדול*", "*כהנ*"])
def test_a_star_at_either_end_is_still_searched(engines, query):
    _search(engines, query)
