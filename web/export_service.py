    def export_browse_word(
        self,
        browse_data: Dict[str, Any]
    ) -> tuple:
        """
        Export browse page data to Word format.

        Returns:
            (bytes, filename) tuple
        """
        if not browse_data:
            raise ValueError("No browse data to export")

        doc = Document()

        # Build title with library name and shelfmark
        shelfmark = browse_data.get('shelfmark', '')
        library_name = browse_data.get('library_name', '')

        # Document title: Library, Shelfmark (or just Shelfmark)
        if library_name and shelfmark:
            doc_title = f"{library_name}, {shelfmark}"
        elif shelfmark:
            doc_title = shelfmark
        else:
            doc_title = 'Genizah Manuscript'

        doc.add_heading(doc_title, 0)

        # Title (Hebrew)
        if browse_data.get('title'):
            add_hebrew_paragraph(doc, browse_data['title'])

        # System ID
        if browse_data.get('sys_id'):
            doc.add_paragraph(f"System ID: {browse_data['sys_id']}")

        doc.add_paragraph("_" * 60)

        # Text content
        if browse_data.get('view_all') and browse_data.get('pages'):
            doc.add_heading('Full Manuscript', 2)
            for page_data in browse_data['pages']:
                doc.add_heading(f"Page {page_data.get('p_num', '?')}", 3)
                if page_data.get('text'):
                    add_hebrew_paragraph(doc, page_data['text'])
        elif browse_data.get('text'):
            doc.add_heading(f"Page {browse_data.get('p_num', '?')}", 2)
            add_hebrew_paragraph(doc, browse_data['text'])

        add_word_credits(doc)

        # Filename: use shelfmark
        filename = make_safe_filename(shelfmark, default="manuscript") + ".docx"
        return save_document_to_bytes(doc), filename


