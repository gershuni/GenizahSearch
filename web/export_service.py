def set_paragraph_rtl(paragraph):
    """Set RTL direction and right alignment for a paragraph containing Hebrew text."""
    paragraph.alignment = WD_PARAGRAPH_ALIGNMENT.RIGHT
    paragraph.paragraph_format.alignment = WD_PARAGRAPH_ALIGNMENT.RIGHT
    ppr = paragraph._p.get_or_add_pPr()
    bidi = ppr.find(qn("w:bidi"))
    if bidi is None:
        bidi = OxmlElement("w:bidi")
        ppr.append(bidi)
    bidi.set(qn("w:val"), "1")


def set_run_rtl_font(run, font_size: Optional[int] = None):
    """Set Hebrew-compatible font for a run and mark it as RTL."""
    run.font.name = HEBREW_FONT_NAME
    r = run._r
    rPr = r.get_or_add_rPr()

    # Set cs (complex script) font for Hebrew
    cs_font = rPr.find(qn("w:rFonts"))
    if cs_font is None:
        cs_font = OxmlElement("w:rFonts")
        rPr.insert(0, cs_font)
    cs_font.set(qn("w:cs"), HEBREW_FONT_NAME)
    cs_font.set(qn("w:ascii"), HEBREW_FONT_NAME)
    cs_font.set(qn("w:hAnsi"), HEBREW_FONT_NAME)

    # Mark as RTL text
    rtl = rPr.find(qn("w:rtl"))
    if rtl is None:
        rtl = OxmlElement("w:rtl")
        rPr.append(rtl)

    if font_size:
        run.font.size = Pt(font_size)


def add_hebrew_paragraph(doc: Document, text: str, bold: bool = False, font_size: Optional[int] = None) -> None:
    """Add a right-aligned Hebrew paragraph to a Word document."""
    p = doc.add_paragraph()
    run = p.add_run(text)
    if bold:
        run.bold = True
    set_run_rtl_font(run, font_size)
    set_paragraph_rtl(p)


def add_highlighted_hebrew_paragraph(doc: Document, text: str) -> None:
    """
    Add a Hebrew paragraph with highlighted terms (marked with *).
    Text between * markers will be bold with yellow highlight.
    """
    p = doc.add_paragraph()
    parts = text.split('*')
    is_highlighted = False

    for i, part in enumerate(parts):
        if not part:
            is_highlighted = not is_highlighted
            continue
        run = p.add_run(part)
        set_run_rtl_font(run)
        if is_highlighted:
            run.bold = True
            # Add yellow highlight
            rPr = run._r.get_or_add_rPr()
            highlight = OxmlElement('w:highlight')
            highlight.set(qn('w:val'), 'yellow')
            rPr.append(highlight)
        is_highlighted = not is_highlighted

    set_paragraph_rtl(p)


def add_word_credits(doc: Document) -> None:
    """Add standard credits section to a Word document."""
    doc.add_page_break()
    doc.add_heading('Credits', 1)
    doc.add_paragraph(CREDITS_TEXT[0])
    doc.add_paragraph(CREDITS_TEXT[1])
    doc.add_paragraph(f'Dataset available at: {CREDITS_TEXT[2].replace("Dataset: ", "")}')
    doc.add_paragraph()
    citation_p = doc.add_paragraph('Full Citation: ')
    citation_run = citation_p.add_run(CREDITS_TEXT[3].replace('Citation: ', ''))
    citation_run.italic = True


