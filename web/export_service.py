@dataclass
class ExcelColumnConfig:
    """Configuration for an Excel column."""
    header: str
    width: int
    alignment: str  # 'rtl', 'ltr', 'center'
    highlight_on_match: bool = False


def create_excel_workbook(
    sheet_name: str = "Results",
    rtl_sheet: bool = True
) -> tuple:
    """
    Create a new Excel workbook with basic configuration.
    Returns (workbook, worksheet).
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = sheet_name[:31]  # Excel sheet name limit
    if rtl_sheet:
        ws.sheet_view.rightToLeft = True
    return wb, ws


def style_excel_header(ws, headers: List[str]) -> None:
    """Apply standard header styling to the first row."""
    ws.append(headers)
    header_font = Font(bold=True, color="FFFFFF")
    header_fill = PatternFill(start_color="4F81BD", end_color="4F81BD", fill_type="solid")
    header_alignment = Alignment(horizontal="center", vertical="center")

    for col_idx, header in enumerate(headers, 1):
        cell = ws.cell(row=1, column=col_idx)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = header_alignment


def set_excel_column_widths(ws, widths: Dict[str, int]) -> None:
    """Set column widths. Keys are column letters (A, B, C, ...)."""
    for col_letter, width in widths.items():
        ws.column_dimensions[col_letter].width = width


def get_cell_alignment(align_type: str) -> Alignment:
    """Get an Alignment object based on alignment type."""
    if align_type == 'rtl':
        return Alignment(horizontal="right", vertical="top", wrap_text=False, readingOrder=2)
    elif align_type == 'center':
        return Alignment(horizontal="center", vertical="top")
    else:  # 'ltr'
        return Alignment(horizontal="left", vertical="top")


def add_excel_credits(ws) -> None:
    """Add standard credits section at the bottom of the worksheet."""
    ws.append([])
    ws.append([])
    credits_start_row = ws.max_row + 1
    ws.append(['Credits'])
    for credit_line in CREDITS_TEXT:
        ws.append([credit_line])

    # Style credits
    credits_font = Font(italic=True, color="555555")
    for row_idx in range(credits_start_row, ws.max_row + 1):
        cell = ws.cell(row=row_idx, column=1)
        cell.font = credits_font


def save_workbook_to_bytes(wb) -> bytes:
    """Save workbook to a bytes buffer and return the content."""
    stream = io.BytesIO()
    wb.save(stream)
    stream.seek(0)
    return stream.read()


def save_document_to_bytes(doc: Document) -> bytes:
    """Save Word document to a bytes buffer and return the content."""
    stream = io.BytesIO()
    doc.save(stream)
    stream.seek(0)
    return stream.read()


