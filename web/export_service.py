                shelf_run.bold = True
                set_run_rtl_font(shelf_run)
                p.add_run(f" - Score: {item.get('score', 0)}")
                set_paragraph_rtl(p)

                # Title
                if title:
                    add_hebrew_paragraph(doc, title)

                # Source Context
                label_p = doc.add_paragraph()
                label_p.add_run("Source Context:").bold = True
